async function request(path, method = "GET", body, expected = 200, authenticated = true) {
  const response = await fetch(`${origin}/api/backend/${path}`, { method,
    headers: { Origin: origin, "Content-Type": "application/json", ...(authenticated && cookie ? { Cookie: cookie } : {}) },
    body: body === undefined ? undefined : JSON.stringify(body) });
  const data = await response.json();
  assert.equal(response.status, expected, `${method} ${path}: ${JSON.stringify(data)}`);
  return { response, data };
}
