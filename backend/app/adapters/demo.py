def _terms(text: str) -> set[str]:
    return set(re.findall(r"[a-z0-9]+", text.lower()))


def _matches(q: Question, filters) -> bool:
    for field in ("subject", "module", "topic"):
        val = getattr(filters, field)
        if val and (not getattr(q, field) or getattr(q, field).lower() != val.lower()):
            return False
    if filters.source_type and q.source.source_type != filters.source_type:
        return False
    if filters.year and q.source.year != filters.year:
        return False
    return True


class DemoQuestions:
    async def catalog(self, trace_id):
        return FilterCatalog(
            combinations=[
                SearchFilters(
                    subject=q.subject,
                    module=q.module,
                    topic=q.topic,
                    year=q.source.year,
                    source_type=q.source.source_type,
                )
                for q in DEMO_QUESTIONS
            ]
        )

    async def search(self, request, trace_id):
        tokens = _terms(request.query)
        results = []
        for q in DEMO_QUESTIONS:
            if not _matches(q, request.filters):
                continue
            haystack = _terms(" ".join((q.text, q.subject, q.module or "", q.topic or "")))
            overlap = len(tokens & haystack)
            if overlap:
                results.append(
                    SearchHit(question=q, relevance_score=round(overlap / max(len(tokens), 1), 3))
                )
        return sorted(results, key=lambda hit: hit.relevance_score or 0, reverse=True)[
            : request.limit
        ]

    async def get(self, question_id, trace_id):
        return next((q for q in DEMO_QUESTIONS if q.id == question_id), None)

    async def similar(self, question_id, limit, trace_id):
        q = await self.get(question_id, trace_id)
        if q is None:
            return []
        return [
            SearchHit(question=other, relevance_score=0.5)
            for other in DEMO_QUESTIONS
            if other.id != question_id and other.module == q.module
        ][:limit]


