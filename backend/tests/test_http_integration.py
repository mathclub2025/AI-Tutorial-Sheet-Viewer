import asyncio
import json

import httpx
from fastapi.testclient import TestClient

from app.adapters.demo import DEMO_QUESTIONS
from app.config import Settings
from app.main import create_app


class Handler:
    def __init__(self):
        self.events = []
        self.ai_calls = []

    def __call__(self, request: httpx.Request) -> httpx.Response:
        assert request.headers.get("x-internal-token") == "internal-test"
        assert request.headers.get("x-request-id")
        path = request.url.path
        if path == "/internal/v1/query-events":
            event = json.loads(request.content)
            self.events.append(event)
            return httpx.Response(200, json={"accepted": True})
        if path == "/internal/v1/search":
            data = json.loads(request.content)
            assert data["query"]
            return httpx.Response(
                200,
                json={
                    "items": [
                        {
                            "question": DEMO_QUESTIONS[0].model_dump(mode="json"),
                            "relevance_score": 0.92,
                        }
                    ]
                },
            )
        if path == "/internal/v1/questions/demo-calc-01":
            return httpx.Response(200, json=DEMO_QUESTIONS[0].model_dump(mode="json"))
        if path == "/internal/v1/questions/missing":
            return httpx.Response(404, json={"error": "not_found"})
        if path == "/internal/v1/questions/demo-calc-01/similar":
            return httpx.Response(200, json={"items": []})
        if path in ["/internal/v1/answer", "/internal/v1/explain"]:
            data = json.loads(request.content)
            self.ai_calls.append(data)
            assert data["request_id"]
            return httpx.Response(
                200,
                json={"answer": "Generated by test fake", "used_question_ids": ["demo-calc-01"]},
            )
        return httpx.Response(404)


def get_app(handler):
    client = httpx.AsyncClient(transport=httpx.MockTransport(handler))
    cfg = Settings(
        _env_file=None,
        backend_mode="http",
        app_env="testing",
        api_key="test-secret",
        person2_base_url="http://person2.test",
        ai_base_url="http://ai.test",
        internal_service_token="internal-test",
        capture_required=True,
    )
    app = create_app(cfg, http_client=client)
    return app, client


def test_full_http_orchestration_contract():
    handler = Handler()
    app, upstream = get_app(handler)
    with TestClient(app) as c:
        headers = {"X-API-Key": "test-secret", "X-Request-ID": "request-integration-1"}
        search = c.post("/api/v1/search", json={"query": "differentiate x^3"}, headers=headers)
        assert search.status_code == 200, search.text
        assert search.json()["captured"] is True
        ask = c.post("/api/v1/ask", json={"query": "differentiate x^3"}, headers=headers)
        assert ask.status_code == 200, ask.text
        assert ask.json()["answer"] == "Generated by test fake"
        assert ask.json()["citations"][0]["question_id"] == "demo-calc-01"
        assert handler.ai_calls[-1]["context"][0]["id"] == "demo-calc-01"
        explain = c.post("/api/v1/questions/demo-calc-01/explain", json={}, headers=headers)
        assert explain.status_code == 200, explain.text
        assert c.get("/api/v1/questions/missing", headers=headers).status_code == 404
        assert c.get("/api/v1/questions/demo-calc-01/similar", headers=headers).status_code == 200
        assert [e["event_type"] for e in handler.events] == ["search", "ask", "explain"]
    asyncio.run(upstream.aclose())


def test_invalid_upstream_shape_returns_502():
    def bad_handler(request):
        if request.url.path.endswith("/query-events"):
            return httpx.Response(200, json={"accepted": True})
        return httpx.Response(200, json={"items": [{"bad": "schema"}]})

    app, client = get_app(bad_handler)
    with TestClient(app) as c:
        res = c.post(
            "/api/v1/search", json={"query": "derivative"}, headers={"X-API-Key": "test-secret"}
        )
        assert res.status_code == 502
        assert res.json()["error"] == "INVALID_UPSTREAM_RESPONSE"
    asyncio.run(client.aclose())


def test_missing_capture_ack_fails_closed():
    def bad_handler(request):
        return httpx.Response(200, json={"accepted": False})

    app, client = get_app(bad_handler)
    with TestClient(app) as c:
        res = c.post(
            "/api/v1/ask", json={"query": "derivative"}, headers={"X-API-Key": "test-secret"}
        )
        assert res.status_code == 502
        assert res.json()["error"] == "CAPTURE_FAILED"
    asyncio.run(client.aclose())
